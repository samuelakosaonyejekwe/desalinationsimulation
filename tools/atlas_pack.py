"""Second stage of tools/atlas_build.py: turn the cached downloads into the data modules js/data/atlas_*.js.

Not run directly — use `python3 tools/atlas_build.py build [--cache DIR] [--out js/data]`.

Storage: numeric tables are quantised to 8/16-bit integers, DEFLATE-compressed and written as base64 text
({ n: byte length, z: base64 }); js/data/atlas_codec.js decodes them. Small tables stay plain JSON.
"""
import base64, csv, datetime, glob, json, math, os, zlib
import numpy as np
import atlas_build as B

MONTHS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC']


def pack(arr):
    raw = arr if isinstance(arr, (bytes, bytearray)) else np.ascontiguousarray(arr).tobytes()
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    return {'n': len(raw), 'z': base64.b64encode(c.compress(raw) + c.flush()).decode()}


def write_module(out, name, header, exports):
    path = os.path.join(out, name)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(''.join('// ' + ln + '\n' for ln in header))
        for k, v in exports.items():
            f.write('export const %s = %s;\n' % (k, json.dumps(v, separators=(',', ':'), ensure_ascii=False)))
    size = os.path.getsize(path)
    B.log('wrote %-22s %8.1f kB' % (name, size / 1000))
    return size


def mtime_month(*paths):
    t = max(os.path.getmtime(p) for p in paths)
    return datetime.datetime.utcfromtimestamp(t).strftime('%Y-%m')


def compand(a, k):
    """Signed square-root companding to int8: fine steps near sea level, coarse steps at depth / altitude."""
    return np.clip(np.round(np.sign(a) * np.sqrt(np.abs(a)) * k), -127, 127).astype(np.int8)


# ------------------------------------------------------------------------------------------------ relief
def build_relief(cache, out):
    fine = B.load_relief(cache)  # 1.5' samples, row 0 = south
    sea = fine < 0
    # base grid: 0.25 degree cell means
    g25 = B.block_mean(fine, 10)
    q = compand(g25, 1.2)
    d = q.copy(); d[:, 1:] = q[:, 1:] - q[:, :-1]
    # coastal tiles: every 0.25 degree cell with a shoreline, plus its shallow sea neighbours, at 0.05 degrees.
    # A 0.05 degree value is the mean of the majority class (sea or land) of its samples, so that a cell which is
    # mostly water reports the depth of the water, not an average pulled up by the land next to it.
    fr = sea.reshape(720, 10, 1440, 10).mean(axis=(1, 3))
    lat = -90 + 0.125 + 0.25 * np.arange(720)
    band = ((lat > -57) & (lat < 72))[:, None]
    coast = (fr > 0.02) & (fr < 0.98) & band
    nb = coast.copy()
    for di in (-1, 0, 1):
        for dj in (-1, 0, 1):
            nb |= np.roll(np.roll(coast, di, 0), dj, 1)
    mask = nb & (fr > 0.02) & ((g25 > -300) | coast) & band
    f4 = fine.reshape(3600, 2, 7200, 2).astype(np.float64)
    s4 = (f4 < 0)
    nsea = s4.sum(axis=(1, 3))
    sea_mean = np.where(nsea > 0, (f4 * s4).sum(axis=(1, 3)) / np.maximum(nsea, 1), 0)
    land_mean = np.where(nsea < 4, (f4 * ~s4).sum(axis=(1, 3)) / np.maximum(4 - nsea, 1), 0)
    c5 = np.where(nsea >= 2, np.minimum(sea_mean, -1), land_mean)
    ii, jj = np.nonzero(mask)
    t = np.stack([c5[i * 5:(i + 1) * 5, j * 5:(j + 1) * 5] for i, j in zip(ii, jj)])
    tq = compand(t, 2.0)
    tq[(t < 0) & (tq == 0)] = -1
    tq[:, 1::2, :] = tq[:, 1::2, ::-1]  # boustrophedon order keeps neighbours adjacent
    tq = tq.reshape(len(tq), 25)
    td = tq.copy(); td[:, 1:] = tq[:, 1:] - tq[:, :-1]
    ids = (ii * 1440 + jj).astype(np.int64)
    idd = np.diff(ids, prepend=0).astype('<i4')
    relief = {'source': 'NOAA NCEI global DEM mosaic (ETOPO 2022, GEBCO and regional surveys), 1.5 arc-minute export', 'vintage': mtime_month(*glob.glob(os.path.join(cache, 'relief/*.tif'))),
              'base': {'step': 0.25, 'nlat': 720, 'nlon': 1440, 'k': 1.2, 'data': pack(d)},
              'tiles': {'step': 0.05, 'per': 5, 'k': 2.0, 'count': int(len(ids)), 'ids': pack(idd), 'data': pack(td)}}
    return write_module(out, 'atlas_relief.js', [
        'Built-in world atlas — seabed depth and land elevation. Generated by tools/atlas_build.py; do not edit.',
        'Source: NOAA NCEI global DEM mosaic. Base grid: 0.25 degree cell means, whole world. Coastal tiles: 0.05 degree',
        '(about 5 km) values for every 0.25 degree cell that holds a shoreline and its shallow sea neighbours, 57 S - 72 N;',
        'each 0.05 degree value is the mean of the majority class (sea or land) of the 1.5 arc-minute samples inside it.',
        'Values are square-root companded to 8 bits: z = sign(q) * (q / k)^2 metres.'], {'RELIEF': relief})


# ------------------------------------------------------------------------------------------------ ocean
def harmonics(m):
    """Annual mean and first two harmonics (a1, b1, a2, b2) of 12 monthly values; value(m) = mean + sum a_k cos + b_k sin."""
    ok = np.isfinite(m)
    if ok.sum() < 8:
        return None
    ph = 2 * np.pi * np.arange(12) / 12
    A = np.stack([np.ones(12), np.cos(ph), np.sin(ph), np.cos(2 * ph), np.sin(2 * ph)], axis=1)
    c, *_ = np.linalg.lstsq(A[ok], m[ok], rcond=None)
    return c


def build_ocean(cache, out):
    from scipy.io import netcdf_file
    import warnings
    # ---- salinity: SeaDataCloud 0.25 degree monthly climatology, 5 m level
    S = []
    for m in range(12):
        f = netcdf_file(os.path.join(cache, 'ocean/Salinity_%02d.nc' % m), 'r', mmap=False)
        a = f.variables['Salinity'][0, 0].astype(np.float64).copy()
        a[a > 1e30] = np.nan
        S.append(a[:640])  # 80 S ... 79.75 N
    S = np.array(S)
    S[(S <= 0) | (S > 50)] = np.nan
    F = 4  # 0.25 degree nodes per cell  ->  1 degree cells
    nlat, nlon = 640 // F, 1440 // F
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        # cell value of a month: median of its nodes (robust against isolated artefacts of the analysis)
        Sc = np.nanmedian(S.reshape(12, nlat, F, nlon, F).transpose(0, 1, 3, 2, 4).reshape(12, nlat, nlon, F * F), axis=3)
    # ---- temperature: CoralTemp monthly means sampled every 0.25 degrees, mean of each calendar month over SST_YEARS
    acc = np.zeros((12, 720, 1440)); cnt = np.zeros((12, 720, 1440))
    for y in B.SST_YEARS:
        for m in range(12):
            f = netcdf_file(os.path.join(cache, 'sst/crw_%d_%02d.nc' % (y, m + 1)), 'r', mmap=False)
            v = f.variables['sea_surface_temperature']
            a = v[0].astype(np.float64) * getattr(v, 'scale_factor', 1.0) + getattr(v, 'add_offset', 0.0)
            if f.variables['latitude'][0] > f.variables['latitude'][-1]:
                a = a[::-1]
            ok = (a > -5) & (a < 45)
            acc[m] += np.where(ok, a, 0); cnt[m] += ok
    clim = np.where(cnt >= max(2, len(B.SST_YEARS) // 2), acc / np.maximum(cnt, 1), np.nan)[:, 40:680]  # 80 S ... 80 N
    ph = 2 * np.pi * np.arange(12) / 12
    def reduce(f):  # block mean over f x f samples, then mean and two harmonics (cells need all twelve months)
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            g = np.nanmean(clim.reshape(12, 640 // f, f, 1440 // f, f), axis=(2, 4))
        ok = np.isfinite(g).all(axis=0)
        g0 = np.nan_to_num(g)
        mean = g0.mean(axis=0)
        co = np.array([(g0 * fn(k * ph)[:, None, None]).sum(axis=0) / 6 for k in (1, 2) for fn in (np.cos, np.sin)])
        return ok, mean, co
    ok1, m1, c1 = reduce(4)   # 1 degree, everywhere
    ok2, m2, c2 = reduce(2)   # 0.5 degree, kept only near land where the coastal gradients are
    near = np.zeros_like(ok2)
    for di in range(-2, 3):
        for dj in range(-2, 3):
            near |= ~np.roll(np.roll(ok2, di, 0), dj, 1)
    keep = ok2 & near
    q16 = lambda ok, mean: np.where(ok, np.round(mean * 100), -32768).astype('<i2')
    q8 = lambda ok, co: np.where(ok[None], np.clip(np.round(co * 8), -127, 127), 0).astype(np.int8)
    s0 = np.full((nlat, nlon), 0xFFFF, dtype='<u2'); sh = np.zeros((4, nlat, nlon), dtype=np.int8)
    ns = 0
    for i in range(nlat):
        for j in range(nlon):
            s = Sc[:, i, j].copy()
            if np.isfinite(s).sum() < 8:
                continue
            # months far from the median of the year are analysis artefacts (seen in the Arabian Gulf): leave them out of the fit
            med = np.nanmedian(s); mad = np.nanmedian(np.abs(s - med))
            s[np.abs(s - med) > max(2.5 * 1.4826 * mad, 0.4)] = np.nan
            cs = harmonics(s)
            if cs is not None:
                s0[i, j] = int(round(float(np.nanmedian(s)) * 100)); sh[:, i, j] = np.clip(np.round(cs[1:] * 20), -127, 127); ns += 1
    B.log('ocean: %d salinity cells; temperature: %d cells at 1 degree, %d coastal cells at 0.5 degree' % (ns, int(ok1.sum()), int(keep.sum())))
    yrs = '%d-%d' % (B.SST_YEARS[0], B.SST_YEARS[-1])
    ocean = {'source': 'Salinity: SeaDataCloud global climatology V2.1 (SeaDataNet; EMODnet Physics ERDDAP), 5 m level. Temperature: NOAA Coral Reef Watch CoralTemp monthly mean sea-surface temperature (NOAA CoastWatch ERDDAP)',
             'vintage': mtime_month(*glob.glob(os.path.join(cache, 'ocean/Salinity_*.nc')), *glob.glob(os.path.join(cache, 'sst/crw_*.nc'))),
             'period': 'salinity: climatological months from observations 1955-2019; temperature: mean of each calendar month ' + yrs, 'sstPeriod': yrs,
             'step': 1, 'lat0': -80, 'lon0': -180, 'nlat': nlat, 'nlon': nlon, 's0': pack(s0), 'sh': pack(sh), 't0': pack(q16(ok1, m1)), 'th': pack(q8(ok1, c1)),
             'fine': {'step': 0.5, 'lat0': -80, 'lon0': -180, 'nlat': 320, 'nlon': 720, 't0': pack(q16(keep, m2)), 'th': pack(q8(keep, c2))}}
    return write_module(out, 'atlas_ocean.js', [
        'Built-in world atlas — near-surface salinity and temperature of the sea. Generated by tools/atlas_build.py; do not edit.',
        '80 S - 80 N. Salinity: SeaDataCloud global climatology V2.1 (0.25 degree, monthly, 5 m level) on 1 degree cells, per cell',
        'the median of the year (g/kg x 100; 65535 = land or no data). Temperature: NOAA CoralTemp monthly mean sea-surface',
        'temperature (5 km, sampled every 0.25 degrees), mean of each calendar month %s, on 1 degree cells everywhere and on' % yrs,
        '0.5 degree cells (`fine`) within two cells of land (annual mean degC x 100; -32768 = land or not stored). Both carry the',
        'first two harmonics of the seasonal cycle (salinity x 20, temperature x 8):',
        'value(month m) = mean + a1 cos(2 pi m/12) + b1 sin(2 pi m/12) + a2 cos(4 pi m/12) + b2 sin(4 pi m/12).'], {'OCEAN': ocean})


