def build_climate(cache, out):
    nlat, nlon = 140, 360  # 60 S ... 80 N, 1 degree
    grids, header = {}, None
    for par in B.POWER_PARAMS:
        acc = np.zeros((13, nlat, nlon)); cnt = np.zeros((nlat, nlon))
        for path in glob.glob(os.path.join(cache, 'power/%s_*.json' % par)):
            j = json.load(open(path))
            header = header or j.get('header')
            for ft in j.get('features', []):
                lo, la = ft['geometry']['coordinates'][:2]
                p = ft['properties']['parameter'][par]
                v = [p.get(m, -999) for m in MONTHS] + [p.get('ANN', -999)]
                if min(v) < -900:
                    continue
                i, jx = int(math.floor(la + 60)), int(math.floor(lo + 180)) % 360
                if 0 <= i < nlat:
                    acc[:, i, jx] += v; cnt[i, jx] += 1
        grids[par] = np.where(cnt > 0, acc / np.maximum(cnt, 1), np.nan)
        B.log('climate %s: %d of %d cells' % (par, int((cnt > 0).sum()), nlat * nlon))
    scale = {'ALLSKY_SFC_SW_DWN': (25, 0), 'WS10M': (12, 0), 'T2M': (2.5, 60)}  # stored = (value + offset) * scale
    hscale = {'ALLSKY_SFC_SW_DWN': 25, 'WS10M': 12, 'T2M': 4}
    ann, har = {}, {}
    ph = 2 * np.pi * np.arange(12) / 12
    for par, g in grids.items():
        k, off = scale[par]
        a = np.where(np.isfinite(g[12]), np.clip(np.round((g[12] + off) * k), 0, 254), 255).astype(np.uint8)
        ann[par] = pack(a)
        # seasonal cycle on 2 degree cells: first two harmonics of the monthly departures from the annual mean
        m = g[:12] - g[:12].mean(axis=0)
        import warnings
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            m2 = np.nanmean(m.reshape(12, nlat // 2, 2, nlon // 2, 2), axis=(2, 4))
        m2 = np.nan_to_num(m2)
        co = [(m2 * f(q * ph)[:, None, None]).sum(axis=0) / 6 for q in (1, 2) for f in (np.cos, np.sin)]
        har[par] = pack(np.clip(np.round(np.array(co) * hscale[par]), -127, 127).astype(np.int8))
    climate = {'source': 'NASA POWER climatology (CERES SYN1deg irradiance, MERRA-2 wind and temperature)', 'vintage': mtime_month(*glob.glob(os.path.join(cache, 'power/*.json'))),
               'period': '%s-%s' % ((header or {}).get('start', '2001')[:4], (header or {}).get('end', '2020')[:4]), 'lat0': -60, 'lon0': -180, 'nlat': nlat, 'nlon': nlon, 'step': 1, 'hstep': 2,
               'ghi': {'k': 25, 'off': 0, 'hk': 25, 'ann': ann['ALLSKY_SFC_SW_DWN'], 'har': har['ALLSKY_SFC_SW_DWN']},
               'wind': {'k': 12, 'off': 0, 'hk': 12, 'ann': ann['WS10M'], 'har': har['WS10M']},
               'temp': {'k': 2.5, 'off': 60, 'hk': 4, 'ann': ann['T2M'], 'har': har['T2M']}}
    return write_module(out, 'atlas_climate.js', [
        'Built-in world atlas — long-term solar, wind and air-temperature resource. Generated by tools/atlas_build.py; do not edit.',
        'Source: NASA POWER climatology API, 2001-2020. Annual means on a 1 degree grid, 60 S - 80 N (all-sky global horizontal',
        'irradiation kWh/m2/d, wind speed at 10 m m/s, air temperature at 2 m degC; stored = (value + off) * k, 255 = no data)',
        'and the first two harmonics of the seasonal cycle on a 2 degree grid (x hk).'], {'CLIMATE': climate})


